SCHEMA = "bic-cognitive-credit-audit-v1"
BUDGETS = (0, 1, 4, 16)
ADAPT_SEED = 3301


def audit_sources():
    result = source_hashes()
    root = Path(__file__).resolve().parents[1]
    for name in ("experiments/audit_cognitive_credit.py", "experiments/audit_cognitive_transfer.py"):
        result[name] = file_hash(root / name)
    return result


def prepared_banks():
    support = make_banks(seed=27_000_000, count=32, families=(HELDOUT_FAMILY,))
    excluded = {transcript(row) for row in support[HELDOUT_FAMILY]}
    queries, exclusions = {}, {}
    for level in (2, 3):
        rows = make_banks(seed=28_000_000, count=256, split="audit",
            levels=(level,), families=(HELDOUT_FAMILY,))[HELDOUT_FAMILY]
        queries[f"level_{level}"], exclusions[f"level_{level}"] = exclude_overlapping_pairs(rows, excluded)
    return {"support": support, "query": queries,
            "main_development": make_banks(seed=24_000_000, count=64, split="dev"),
            "retained": make_banks(seed=29_000_000, count=64, split="dev"),
            "advanced": make_banks(seed=26_000_000, count=256, split="audit", levels=(3,))}, exclusions


def prepare(directory, *, seed=2301):
    if type(seed) is not int or not 0 <= seed < 2**63:
        raise ValueError("initial seed must be a nonnegative int64")
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    with run_lock(directory):
        banks, exclusions = prepared_banks()
        contract = {"schema": SCHEMA, "source_sha256": audit_sources(), "seed": seed,
            "aux_weights": [0., .3], "adaptation_aux_weight": 0.,
            "adaptation_seed": ADAPT_SEED, "adaptation_updates": list(BUDGETS),
            "learning_rate": .003, "batch_size": 64, "planned_main_updates": 1800,
            "checkpoint_every": 300, "train_seed": 20_000_000,
            "train_count_per_family_level": 512, "train_levels": [1, 2],
            "training_families": list(TRAIN_FAMILIES), "heldout_family": HELDOUT_FAMILY,
            "memory_mode": "recurrent", "schedule": "interleaved",
            "bank_seeds": {"main_development": 24_000_000, "advanced": 26_000_000,
                           "support": 27_000_000, "query": 28_000_000, "retained": 29_000_000},
            "banks": bank_manifest(banks), "support_overlap_whole_pair_exclusions": exclusions,
            "exposure_sha256": exposure_hashes(seed, steps=1800, batch_size=64, lessons=512),
            "screen": {"main_macro_pair_gain": .10, "family_pair_gain": .05, "families_required": 2,
                "max_family_query_loss": .05, "later_known_macro_gain": .05,
                "later_known_family_gain": .05, "max_later_known_family_loss": .05,
                "max_adaptation_auc_loss": .02, "max_graph_later_query_loss": .02,
                "max_graph_later_pair_loss": .02, "max_retention_macro_loss": .02,
                "max_retention_family_query_loss": .05},
            "later_query_definition": "Last known-answer query in each episode, included only when its "
                "ordinal among all queries is at least two. Missing denominators do not pass.",
            "interpretation": "One initialization, one heldout-family rotation, one adaptation support "
                "draw on an already inspected procedural grammar. Exploratory screen; no promotion."}
        path = directory / "manifest.json"
        if path.exists():
            prior = json.loads(path.read_text(encoding="utf8"))
            if {key: val for key, val in prior.items() if key != "prepared_utc"} != contract:
                raise ValueError("prepared audit contract changed; use a new directory")
            load_prepared(directory)
            return prior
        contract["prepared_utc"] = datetime.now(timezone.utc).isoformat()
        atomic_json(directory / "banks.json", banks)
        atomic_json(path, contract)
        return contract


def load_prepared(directory):
    directory = Path(directory)
    manifest = json.loads((directory / "manifest.json").read_text(encoding="utf8"))
    banks = json.loads((directory / "banks.json").read_text(encoding="utf8"))
    if manifest.get("schema") != SCHEMA or manifest["source_sha256"] != audit_sources():
        raise ValueError("audit source mismatch")
    if manifest["banks"] != bank_manifest(banks):
        raise ValueError("audit bank mismatch")
    return manifest, banks


def verify_runs(paths, manifest):
    if len(paths) != 2:
        raise ValueError("exactly two completed matched arms are required")
    records, seen, common, initial_digest = [], set(), None, None
    prepared = datetime.fromisoformat(manifest["prepared_utc"]).timestamp()
    expected_draws = manifest["exposure_sha256"]
    for value in paths:
        path = Path(value).resolve()
        protocol = json.loads((path / "protocol.json").read_text(encoding="utf8"))
        report = json.loads((path / "report.json").read_text(encoding="utf8"))
        saved = torch.load(path / "latest.pt", map_location="cpu", weights_only=True)
        weight = protocol["aux_weight"]
        if weight not in manifest["aux_weights"] or weight in seen:
            raise ValueError("requires distinct auxiliary weights zero and 0.3")
        seen.add(weight)
        if (protocol["schema"] != "bic-credit-training-v1" or protocol["seed"] != manifest["seed"]
                or protocol["steps"] != 1800 or report["updates"] != 1800
                or saved["training"]["updates"] != 1800 or report["stop_reason"] != "planned_updates"
                or report["heldout_evaluation_performed"] or saved["protocol"] != protocol
                or report["protocol"] != protocol):
            raise ValueError("incomplete run or inconsistent protocol")
        checks = {"batch_size": 64, "checkpoint_every": 300, "learning_rate": .003,
            "memory_mode": "recurrent", "schedule": "interleaved", "train_levels": [1, 2],
            "training_families": list(TRAIN_FAMILIES), "heldout_family": HELDOUT_FAMILY,
            "train_bank_seed": 20_000_000, "dev_seed": 24_000_000,
            "train_count_per_family_level": 512, "within_family_draw_sha256": expected_draws}
        if any(protocol[key] != expected for key, expected in checks.items()):
            raise ValueError("run settings, heldout boundary, or exposures differ from the audit")
        expected_counts = {family: 600 for family in TRAIN_FAMILIES}
        if report["family_updates"] != expected_counts or saved["training"]["family_updates"] != expected_counts:
            raise ValueError("family update counts differ")
        if protocol["source_sha256"] != source_hashes():
            raise ValueError("training source changed")
        for name, digest in protocol["source_sha256"].items():
            if file_hash(path / "source" / name) != digest:
                raise ValueError("frozen training source snapshot changed")
        if (path / "initial.pt").stat().st_mtime < prepared:
            raise ValueError("audit preparation must precede initial checkpoints")
        comparison = {key: val for key, val in protocol.items() if key != "aux_weight"}
        if common is not None and comparison != common:
            raise ValueError("matched protocols differ beyond the auxiliary coefficient")
        common = comparison
        model = build_credit_student(manifest["seed"])
        fresh_digest = checkpoint_digest(model)
        initial = torch.load(path / "initial.pt", map_location="cpu", weights_only=True)
        model.load_state_dict(initial["weights"])
        digest = checkpoint_digest(model)
        if digest != fresh_digest or (initial_digest is not None and digest != initial_digest):
            raise ValueError("initial policy or auxiliary weights differ")
        initial_digest = digest
        _check_finite_tree(saved["training"]["weights"], "audited_weights")
        model.load_state_dict(saved["training"]["weights"])
        if checkpoint_digest(model) != report["checkpoint_sha256"]:
            raise ValueError("final report and checkpoint weights disagree")
        train = make_banks()
        dataset = json.loads((path / "datasets.json").read_text(encoding="utf8"))
        if dataset["training"] != {key: fingerprint_rows(rows) for key, rows in train.items()}:
            raise ValueError("training bank fingerprint mismatch")
        records.append({"key": f"aux-{weight:g}", "path": str(path), "aux_weight": weight,
            "checkpoint_sha256": file_hash(path / "latest.pt"),
            "weights": saved["training"]["weights"], "training_banks": train})
    return sorted(records, key=lambda row: row["aux_weight"])


def last_known_later_mask(labels):
    """labels [turn,batch]; query ordinals count unknown queries as well."""
    query = labels.ne(ACK)
    ordinal = query.long().cumsum(0)
    known = labels.lt(2)
    selected = torch.zeros_like(query)
    for index in range(labels.shape[1]):
        positions = known[:, index].nonzero().flatten()
        if positions.numel() and ordinal[positions[-1], index] >= 2:
            selected[positions[-1], index] = True
    return selected


def position_metrics(predictions, labels, rows, reply_correct=None):
    query = labels.ne(ACK)
    ordinal = query.long().cumsum(0)
    groups = {}
    for index, row in enumerate(rows):
        groups.setdefault(row["counterfactual_group"], []).append(index)
    if any(len(members) != 2 for members in groups.values()):
        raise ValueError("position scores require complete counterfactual groups")

    def score(mask):
        total = int(mask.sum())
        correct = int((predictions.eq(labels) & mask).sum())
        pair_total = pair_correct = 0
        for left, right in groups.values():
            eligible = mask[:, left] & mask[:, right] & labels[:, left].ne(labels[:, right])
            pair_total += int(eligible.sum())
            pair_correct += int((eligible & predictions[:, left].eq(labels[:, left])
                                 & predictions[:, right].eq(labels[:, right])).sum())
        return {"total": total, "correct": correct, "accuracy": correct / total if total else None,
            "predicted_action_counts": torch.bincount(predictions[mask], minlength=4).cpu().tolist(),
            "reply_exact_correct": int((reply_correct & mask).sum()) if reply_correct is not None else None,
            "reply_exact_accuracy": float(reply_correct[mask].float().mean())
                if reply_correct is not None and total else None,
            "pairs": {"total": pair_total, "correct": pair_correct,
                      "accuracy": pair_correct / pair_total if pair_total else None}}

    def slices(mask):
        return {"all": score(mask), "known": score(mask & labels.lt(2)),
                "unknown": score(mask & labels.eq(2))}

    by_turn = []
    for turn in range(labels.shape[0]):
        mask = torch.zeros_like(query)
        mask[turn] = query[turn]
        if bool(mask.any()):
            by_turn.append({"turn_one_based": turn + 1, "slices": slices(mask)})
    return {"by_turn": by_turn,
            "by_query_ordinal": [{"query_ordinal": index, "slices": slices(query & ordinal.eq(index))}
                for index in range(1, int(ordinal.max()) + 1)],
            "last_known_later_query": score(last_known_later_mask(labels))}


def score_positions(model, rows, *, replies=False, blank_text=False, reset_each_turn=False):
    before = checkpoint_digest(model)
    modes = [(module, module.training) for module in model.modules()]
    try:
        model.eval()
        with torch.inference_mode():
            state = None
            predictions, labels, reply_correct = [], [], []
            for batch in encode_dialogues(model, rows, blank_text=blank_text):
                decoder = torch.full((len(rows), 1), ByteCodec.BOS, dtype=torch.long, device=batch["text_ids"].device)
                output, state = _run_turn(model, batch, None if reset_each_turn else state, decoder=decoder)
                predictions.append(output["logits"][:, -1].argmax(-1))
                labels.append(batch["targets"])
                if replies:
                    reply_correct.append(_exact_replies(_generate_reply_tokens(model, output["production_context"]),
                                                        batch["reply_targets"]))
            return position_metrics(torch.stack(predictions), torch.stack(labels), rows,
                                    torch.stack(reply_correct) if replies else None)
    finally:
        for module, training in modes:
            module.training = training
        if checkpoint_digest(model) != before:
            raise RuntimeError("position evaluation changed weights")


def score_banks(model, banks, *, replies=False, **controls):
    values = {}
    for key, rows in banks.items():
        values[key] = {**evaluate_bank(model, rows, replies=replies, **controls),
                      "positions": score_positions(model, rows, replies=replies, **controls)}
    later = [row["positions"]["last_known_later_query"]["accuracy"] for row in values.values()]
    return {"per_bank": values,
            "macro_query_accuracy": sum(row["query_accuracy"] for row in values.values()) / len(values),
            "macro_pair_accuracy": sum(row["counterfactual_accuracy"] or 0 for row in values.values()) / len(values),
            "macro_later_known_accuracy": sum(later) / len(later) if None not in later else None}


def fresh_adaptation(weights, support, *, device="cpu"):
    trainer = CreditTrainer(support, seed=ADAPT_SEED, memory_mode="recurrent", device=device,
                            batch_size=64, learning_rate=.003, aux_weight=0.)
    trainer.model.load_state_dict(weights, strict=True)
    if trainer.optimizer.state or trainer.updates or trainer.aux_weight != 0.:
        raise RuntimeError("adaptation must reset optimizer and disable auxiliary teaching")
    return trainer


def cpu_restart(weights, episode, *, seed):
    model = build_credit_student(seed)
    model.load_state_dict(weights)
    model.eval()
    digest = checkpoint_digest(model)
    with torch.inference_mode():
        batches = encode_dialogues(model, [episode])
        decoder = torch.full((1, 1), ByteCodec.BOS, dtype=torch.long)
        state = None
        for batch in batches[:3]:
            _, state = _run_turn(model, batch, state, decoder=decoder)
        stream = io.BytesIO()
        torch.save({"weights": _cpu_copy(model.state_dict()),
                    "state": model.state_to_dict(state, checkpoint_sha256=digest)}, stream)
        stream.seek(0)
        payload = torch.load(stream, map_location="cpu", weights_only=True)
        restored = build_credit_student(seed)
        restored.load_state_dict(payload["weights"])
        restored.eval()
        restarted = restored.state_from_dict(payload["state"], checkpoint_sha256=checkpoint_digest(restored))
        for batch in batches[3:]:
            a, state = _run_turn(model, batch, state, decoder=decoder)
            b, restarted = _run_turn(restored, batch, restarted, decoder=decoder)
            if any(not torch.equal(a[key], b[key]) for key in ("logits", "language_logits", "production_context")):
                raise RuntimeError("CPU continuation differs after serialization")
            if not torch.equal(_generate_reply_tokens(model, a["production_context"]),
                               _generate_reply_tokens(restored, b["production_context"])):
                raise RuntimeError("CPU generated continuation differs")
    return {"exact": True, "serialized_after_turn": 3, "checked_remaining_turns": 3,
            "device": "cpu", "checkpoint_sha256": digest, "includes_auxiliary_weights": True}


def adapt_candidate(weights, banks, *, seed, device="cpu"):
    started = time.monotonic()
    trainer = fresh_adaptation(weights, banks["support"], device=device)
    initial_digest = checkpoint_digest(trainer.model)
    main = score_banks(trainer.model, banks["main_development"], replies=True)
    retained_before = score_banks(trainer.model, banks["retained"], replies=True)
    advanced_before = score_banks(trainer.model, banks["advanced"], replies=True)
    curve, training_seconds = [], 0.
    for budget in BUDGETS:
        while trainer.updates < budget:
            start = time.monotonic()
            trainer.step(HELDOUT_FAMILY)
            training_seconds += time.monotonic() - start
        curve.append({"updates": budget, "support_exposures": budget * 64,
            **score_banks(trainer.model, banks["query"], replies=budget == 16)})
    retained_after = score_banks(trainer.model, banks["retained"], replies=True)
    advanced_after = score_banks(trainer.model, banks["advanced"], replies=True)
    controls = {name: score_banks(trainer.model, banks["query"], **kwargs)
        for name, kwargs in (("blank_text", {"blank_text": True}),
                             ("reset_each_turn", {"reset_each_turn": True}))}
    auc = sum((right["updates"] - left["updates"]) *
        (right["macro_query_accuracy"] + left["macro_query_accuracy"]) / 2
        for left, right in zip(curve, curve[1:])) / 16
    snapshot = trainer.snapshot()
    return {"initial_weight_sha256": initial_digest, "main_development": main,
        "adaptation_aux_weight": 0., "optimizer_reset": True, "adaptation_seed": ADAPT_SEED,
        "curve": curve, "normalized_adaptation_auc": auc,
        "retention_before": retained_before, "retention_after": retained_after,
        "advanced_before": advanced_before, "advanced_after": advanced_after,
        "controls_at_16": controls, "training_seconds": training_seconds,
        "wall_seconds": time.monotonic() - started,
        "cpu_restart": cpu_restart(snapshot["weights"], banks["query"]["level_2"][0], seed=seed),
        "final_weight_sha256": checkpoint_digest(trainer.model)}, snapshot


def benefit_screen(candidate, control, thresholds):
    """All signs are candidate minus matched control; None fails measurement."""
    requirements = {}
    def require(name, c, b, minimum):
        requirements[name] = None if c is None or b is None else bool(c - b >= minimum - 1e-9)
    c, b = candidate["main_development"], control["main_development"]
    require("main_macro_pair_gain", c["macro_pair_accuracy"], b["macro_pair_accuracy"], thresholds["main_macro_pair_gain"])
    pair_gains = {family: c["per_bank"][family]["counterfactual_accuracy"] - b["per_bank"][family]["counterfactual_accuracy"]
                  for family in TRAIN_FAMILIES}
    requirements["two_family_pair_gains"] = sum(value >= thresholds["family_pair_gain"] - 1e-9 for value in pair_gains.values()) >= 2
    require("main_macro_later_known_gain", c["macro_later_known_accuracy"], b["macro_later_known_accuracy"], thresholds["later_known_macro_gain"])
    later_gains = {}
    for family in TRAIN_FAMILIES:
        cr, br = c["per_bank"][family], b["per_bank"][family]
        require(f"main_{family}_query_retention", cr["query_accuracy"], br["query_accuracy"], -thresholds["max_family_query_loss"])
        ca, ba = (row["positions"]["last_known_later_query"]["accuracy"] for row in (cr, br))
        later_gains[family] = None if ca is None or ba is None else ca - ba
        require(f"main_{family}_later_retention", ca, ba, -thresholds["max_later_known_family_loss"])
    requirements["two_family_later_gains"] = sum(value is not None and value >= thresholds["later_known_family_gain"] - 1e-9 for value in later_gains.values()) >= 2
    require("graph_adaptation_auc", candidate["normalized_adaptation_auc"], control["normalized_adaptation_auc"], -thresholds["max_adaptation_auc_loss"])
    for level in ("level_2", "level_3"):
        cr, br = (row["curve"][-1]["per_bank"][level]["positions"]["last_known_later_query"] for row in (candidate, control))
        require(f"graph_{level}_later_query", cr["accuracy"], br["accuracy"], -thresholds["max_graph_later_query_loss"])
        require(f"graph_{level}_later_pairs", cr["pairs"]["accuracy"], br["pairs"]["accuracy"], -thresholds["max_graph_later_pair_loss"])
    for phase in ("retention_before", "retention_after"):
        cr, br = candidate[phase], control[phase]
        for metric in ("macro_query_accuracy", "macro_pair_accuracy"):
            require(f"{phase}_{metric}", cr[metric], br[metric], -thresholds["max_retention_macro_loss"])
        for family in TRAIN_FAMILIES:
            require(f"{phase}_{family}_query", cr["per_bank"][family]["query_accuracy"], br["per_bank"][family]["query_accuracy"], -thresholds["max_retention_family_query_loss"])
    return {"passed": all(value is True for value in requirements.values()),
            "requirements": requirements, "main_pair_gains_by_family": pair_gains,
            "main_later_known_gains_by_family": later_gains,
            "interpretation": "Exploratory confirmation screen; no automatic promotion."}


def audit(paths, directory, *, device="cpu"):
    torch.set_num_threads(1)
    directory = Path(directory)
    with run_lock(directory):
        manifest, banks = load_prepared(directory)
        runs = verify_runs(paths, manifest)
        training_text = {transcript(row) for rows in runs[0]["training_banks"].values() for row in rows}
        exclusions = {}
        for group in ("main_development", "retained", "advanced"):
            exclusions[group] = {}
            for name, rows in banks[group].items():
                banks[group][name], exclusions[group][name] = exclude_overlapping_pairs(rows, training_text)
        inputs = {"schema": SCHEMA, "manifest_sha256": file_hash(directory / "manifest.json"), "device": device,
            "runs": [{key: row[key] for key in ("key", "path", "checkpoint_sha256")} for row in runs],
            "whole_pair_exclusions": exclusions, "evaluated_banks": bank_manifest(banks)}
        marker = directory / "evaluation-started.json"
        if marker.exists() and json.loads(marker.read_text(encoding="utf8")) != inputs:
            raise ValueError("audit already started with different inputs")
        atomic_json(marker, inputs)
        if (directory / "report.json").exists():
            return json.loads((directory / "report.json").read_text(encoding="utf8"))
        candidates = [(row["key"], row["weights"]) for row in runs]
        candidates.append(("fresh", _cpu_copy(build_credit_student(manifest["seed"]).state_dict())))
        results = {}
        for key, weights in candidates:
            path = directory / f"{key}.json"
            if path.exists():
                results[key] = json.loads(path.read_text(encoding="utf8"))
                continue
            result, saved = adapt_candidate(weights, banks, seed=manifest["seed"], device=device)
            result["candidate"] = key
            atomic_checkpoint(directory / f"{key}-adapted.pt", saved)
            atomic_json(path, result)
            results[key] = result
            print(json.dumps({"candidate": key, "main_pairs": result["main_development"]["macro_pair_accuracy"],
                "main_later_known": result["main_development"]["macro_later_known_accuracy"],
                "graph_query_at_16": result["curve"][-1]["macro_query_accuracy"],
                "adaptation_auc": result["normalized_adaptation_auc"]}), flush=True)
        if audit_sources() != manifest["source_sha256"]:
            raise RuntimeError("audit source changed while evaluating")
        for row in runs:
            if file_hash(Path(row["path"]) / "latest.pt") != row["checkpoint_sha256"]:
                raise RuntimeError("main checkpoint changed during audit")
        report = {"schema": SCHEMA, "manifest": manifest, "inputs": inputs, "results": results,
            "benefit_screen": benefit_screen(results["aux-0.3"], results["aux-0"], manifest["screen"]),
            "base_checkpoints_unchanged": True, "official_scoring_uses_auxiliary_logits": False,
            "prior_learning_gain_over_fresh_auc": {row["key"]: results[row["key"]]["normalized_adaptation_auc"] - results["fresh"]["normalized_adaptation_auc"] for row in runs},
            "interpretation": manifest["interpretation"]}
        atomic_json(directory / "report.json", report)
        return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--prepare", type=Path)
    parser.add_argument("--seed", type=int, default=2301)
    parser.add_argument("--runs", nargs="+", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--device", choices=("cpu", "cuda"), default="cpu")
    args = parser.parse_args()
    if args.prepare:
        if args.runs or args.output:
            parser.error("preparation is separate from --runs/--output")
        manifest = prepare(args.prepare, seed=args.seed)
        print(json.dumps({"prepared": str(args.prepare), "seed": manifest["seed"], "banks": manifest["banks"]}))
    else:
        if not args.runs or not args.output:
            parser.error("audit requires --runs and a prepared --output")
        result = audit(args.runs, args.output, device=args.device)
        print(json.dumps({"complete": True, "benefit_screen_passed": result["benefit_screen"]["passed"]}))


if __name__ == "__main__":
    main()
