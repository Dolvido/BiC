class FixedCategorySpy(nn.Module):
    """Fixed actions make control observations identical while exposing input/state calls."""
    def __init__(self):
        super().__init__()
        self.anchor = nn.Parameter(torch.zeros(()))
        self.calls = []

    def forward_with_state(self, observations, state=None):
        self.calls.append(({key: value.clone() for key, value in observations.items()}, state))
        logits = self.anchor.new_zeros(observations["visual"].shape[0], 1, 4)
        logits[:, :, 2] = 1
        return {"logits": logits}, len(self.calls)


class AdaptationExperimentTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.old_threads = torch.get_num_threads()
        torch.set_num_threads(1)

    @classmethod
    def tearDownClass(cls):
        torch.set_num_threads(cls.old_threads)

    def setUp(self):
        torch.manual_seed(874)
        self.layouts, self.other_layouts = split_layouts(7001)

    def test_metrics_hand_computed_censoring_and_success_does_not_erase_failed_category(self):
        # Within each phase a category fails, succeeds, then fails again. Earlier
        # failure remains relevant, even though this artificial reward sequence
        # is not generated by the deterministic world.
        rewards = [0, 1, 0, 1, 1, 1, 0, 0, 1, 0, 1, 1]
        categories = [2, 2, 2, 1, 1, 1, 3, 3, 3, 3, 0, 0]
        actual = episode_metrics(rewards, categories, reversal=6)
        expected = {
            "reward": 7 / 12, "late_reward": 7 / 12,
            "initial_late_reward": 4 / 6, "reversal_late_reward": 3 / 6,
            "post_reversal_reward": 3 / 6,
            "initial_first4_reward": 2 / 4, "reversal_first4_reward": 1 / 4,
            "initial_recovery_trials": 6, "reversal_recovery_trials": 7,
            "initial_recovery_failed": 0, "reversal_recovery_failed": 1,
            "initial_repeated_errors": 1, "reversal_repeated_errors": 2,
            "initial_repeated_error_rate": 1 / 6, "reversal_repeated_error_rate": 2 / 6,
        }
        self.assertEqual(set(actual), set(expected))
        for key, value in expected.items():
            with self.subTest(metric=key):
                self.assertAlmostEqual(actual[key], value)

    def test_metrics_three_success_confirmation_and_phase_reset_of_error_history(self):
        perfect = episode_metrics([1] * 6, [0] * 6, reversal=3)
        self.assertEqual(perfect["initial_recovery_trials"], 3)
        self.assertEqual(perfect["reversal_recovery_trials"], 3)
        self.assertEqual(perfect["initial_recovery_failed"], 0)
        self.assertEqual(perfect["reversal_recovery_failed"], 0)
        self.assertEqual(perfect["late_reward"], 1)
        failed = episode_metrics([0] * 6, [2] * 6, reversal=3)
        self.assertEqual(failed["initial_recovery_trials"], 4)
        self.assertEqual(failed["reversal_recovery_trials"], 4)
        self.assertEqual(failed["initial_recovery_failed"], 1)
        self.assertEqual(failed["reversal_recovery_failed"], 1)
        self.assertEqual(failed["initial_repeated_errors"], 2)
        self.assertEqual(failed["reversal_repeated_errors"], 2)

    def test_late_reward_uses_last_eight_per_phase_not_last_sixteen_overall(self):
        # Unequal phases ensure the phase-balanced suffix definition matters.
        initial = [0] * 4 + [1] * 8
        after = [0] * 10
        metrics = episode_metrics(initial + after, [0] * 22, reversal=12)
        self.assertEqual(metrics["reward"], 8 / 22)
        self.assertEqual(metrics["initial_late_reward"], 1)
        self.assertEqual(metrics["reversal_late_reward"], 0)
        self.assertEqual(metrics["late_reward"], .5)

    def test_training_corpus_is_deterministic_normalized_and_only_public_channels(self):
        random_state, tensor_state = random.getstate(), torch.random.get_rng_state().clone()
        first, targets = training_data(3, 4510, self.layouts)
        second, other_targets = training_data(3, 4510, self.layouts)
        self.assertEqual(random.getstate(), random_state)
        self.assertTrue(torch.equal(torch.random.get_rng_state(), tensor_state))
        self.assertEqual(set(first), {"visual", "auditory", "body", "feedback", "tokens"})
        for key, width in (("visual", 16), ("auditory", 4), ("body", 4), ("feedback", 2)):
            self.assertEqual(tuple(first[key].shape), (3, 40, width))
            self.assertEqual(first[key].dtype, torch.float32)
            self.assertTrue(torch.equal(first[key], second[key]))
        self.assertEqual(tuple(first["tokens"].shape), (3, 40))
        self.assertEqual(first["tokens"].dtype, torch.long)
        self.assertEqual(int(first["tokens"].sum()), 0)
        self.assertEqual(tuple(targets.shape), (3, 40, 4))
        self.assertTrue(torch.equal(targets, other_targets))
        self.assertTrue(torch.isfinite(targets).all())
        self.assertTrue(torch.all(targets >= 0))
        torch.testing.assert_close(targets.sum(-1), torch.ones(3, 40))
        self.assertTrue(torch.equal(targets[:, 0], torch.full((3, 4), .25)))
        self.assertTrue(torch.equal(first["feedback"][:, 0], torch.zeros(3, 2)))
        self.assertTrue(torch.all(first["feedback"][:, 1:, 1] == 1))
        self.assertTrue(torch.all(first["body"][:, :, 0] == 1))
        self.assertTrue(torch.all(first["body"][:, :, 2:] == 0))
        self.assertTrue(torch.equal(first["body"][:, :, 1], first["feedback"][:, :, 1]))
        decoded_layouts = first["visual"].reshape(3, 40, 4, 4).argmax(-1)
        self.assertTrue(all(tuple(layout) in self.layouts for layout in decoded_layouts.flatten(0, 1).tolist()))
        # The first correction can use only the immediately observed outcome.
        for row in range(3):
            previous = int(first["auditory"][row, 1].argmax())
            rewarded = bool(first["feedback"][row, 1, 0])
            expected = torch.full((4,), 1 / 3)
            expected[previous] = 0
            if rewarded:
                expected.zero_()
                expected[previous] = 1
            torch.testing.assert_close(targets[row, 1], expected)

    def test_training_teacher_never_reads_privileged_state_or_current_outcome(self):
        original_step = RuleWorld.step
        original_target = RuleWorld.evaluator_target_category
        original_probabilities = CandidateLearner.probabilities
        stepping = [False]
        teacher_inputs = []

        def step(world, action):
            stepping[0] = True
            try:
                return original_step(world, action)
            finally:
                stepping[0] = False

        def target(world):
            self.assertTrue(stepping[0], "hidden rule read outside the environment reward calculation")
            return original_target(world)

        def probabilities(teacher, observation):
            self.assertFalse(stepping[0])
            self.assertEqual(set(observation), {"layout", "previous_category", "reward"})
            teacher_inputs.append(observation)
            return original_probabilities(teacher, observation)

        blocked = AssertionError("privileged state must not reach the training teacher")
        with patch.object(RuleWorld, "step", step), \
             patch.object(RuleWorld, "evaluator_target_category", target), \
             patch.object(RuleWorld, "evaluator_state", side_effect=blocked), \
             patch.object(RuleWorld, "snapshot", side_effect=blocked), \
             patch.object(RuleWorld, "export_history", side_effect=blocked), \
             patch.object(CandidateLearner, "probabilities", probabilities):
            _, targets = training_data(2, 5930, self.layouts)
        self.assertEqual(len(teacher_inputs), 80)
        self.assertEqual(targets.shape, (2, 40, 4))
        self.assertIsNone(teacher_inputs[0]["reward"])
        self.assertIsNone(teacher_inputs[1]["reward"])

    def test_world_factory_layout_split_and_schedule_are_reproducible(self):
        first = make_worlds(8, 810, self.layouts, (12, 28))
        second = make_worlds(8, 810, self.layouts, (12, 28))
        self.assertFalse(set(self.layouts) & set(self.other_layouts))
        self.assertEqual(len(self.layouts), 18)
        self.assertEqual(len(self.other_layouts), 6)
        for a, b in zip(first, second):
            self.assertEqual(a.snapshot(), b.snapshot())
            self.assertIn(tuple(a.observe()["layout"]), self.layouts)
            self.assertTrue(12 <= a.evaluator_state()["reversal_step"] <= 28)

    def test_evaluation_candidate_baseline_small_count_and_trace_contract(self):
        result = evaluate(None, count=8, seed_start=7110, layouts=self.layouts,
                          reversal_range=(10, 30), variant="candidate", traces=True)
        again = evaluate(None, count=8, seed_start=7110, layouts=self.layouts,
                         reversal_range=(10, 30), variant="candidate", traces=True)
        self.assertEqual(result, again)
        self.assertEqual(result["count"], 8)
        self.assertEqual(len(result["episodes"]), 8)
        self.assertEqual(len(result["trajectories"]), 8)
        self.assertGreaterEqual(result["summary"]["reward"], .85)
        self.assertEqual(result["summary"]["late_reward"], 1)
        self.assertEqual(result["summary"]["initial_recovery_failed"], 0)
        self.assertEqual(result["summary"]["reversal_recovery_failed"], 0)
        for episodes, trajectory, traces in zip(result["episodes"], result["trajectories"], result["traces"]):
            self.assertEqual(len(traces), 40)
            self.assertEqual(episodes, episode_metrics(trajectory["rewards"], trajectory["categories"], trajectory["reversal_step"]))
            for index, row in enumerate(traces):
                observation = row["observation"]
                self.assertEqual(set(observation), {"layout", "previous_category", "reward"})
                self.assertEqual(observation["layout"][row["cell"]], row["category"])
                self.assertEqual(row["reward"], trajectory["rewards"][index])
                self.assertEqual(observation["reward"], None if index == 0 else traces[index-1]["reward"])
                self.assertEqual(observation["previous_category"], None if index == 0 else traces[index-1]["category"])
        for metric in result["summary"]:
            self.assertAlmostEqual(result["summary"][metric], sum(row[metric] for row in result["episodes"]) / 8)

    def test_control_reset_retains_feedback_and_feedback_mask_retains_previous_choice(self):
        models = {name: FixedCategorySpy() for name in ("persistent", "reset_state", "no_feedback")}
        for variant, model in models.items():
            evaluate(model, count=8, seed_start=8650, layouts=self.layouts,
                     reversal_range=(10, 30), variant=variant)
        positive_rewards_seen = 0
        for index in range(40):
            persistent, persistent_state = models["persistent"].calls[index]
            reset, reset_state = models["reset_state"].calls[index]
            masked, masked_state = models["no_feedback"].calls[index]
            self.assertIsNone(reset_state)
            self.assertEqual(persistent_state, None if index == 0 else index)
            self.assertEqual(masked_state, persistent_state)
            for key in persistent:
                self.assertTrue(torch.equal(persistent[key], reset[key]), key)
                if key != "feedback":
                    self.assertTrue(torch.equal(persistent[key], masked[key]), key)
            self.assertTrue(torch.equal(persistent["feedback"][:, :, 1], masked["feedback"][:, :, 1]))
            self.assertEqual(int(torch.count_nonzero(masked["feedback"][:, :, 0])), 0)
            positive_rewards_seen += int(torch.count_nonzero(persistent["feedback"][:, :, 0]))
        self.assertGreater(positive_rewards_seen, 0)

    def test_random_model_evaluation_preserves_weights_and_all_outputs_are_finite(self):
        for kind in ("bic", "gru"):
            model = build_model(kind, hidden_size=4)
            before = model_digest(model)
            result = evaluate(model, count=2, seed_start=77120, layouts=self.layouts,
                              reversal_range=(10, 30), variant="persistent")
            self.assertEqual(model_digest(model), before)
            self.assertEqual(result["variant"], "persistent")
            self.assertEqual(result["count"], 2)
            self.assertNotIn("traces", result)
            for value in result["summary"].values():
                self.assertTrue(torch.isfinite(torch.tensor(value)))
            self.assertTrue(0 <= result["summary"]["reward"] <= 1)


